export function isPlantao24h(date) {
  const d = date instanceof Date ? date : new Date(date);
  const dow = d.getDay();
  if (dow === 0 || dow === 6) return true;
  return FERIADOS_2026.has(toDateKey(d));
}

export function getHorarioPlantao(date) {
  return isPlantao24h(date)
    ? { inicio: '07:00', fim: '07:00', duracao: 24 }
    : { inicio: '19:00', fim: '07:00', duracao: 12 };
}

export function getPlantaoEfetivo(now = new Date()) {
  const d = new Date(now);
  if (d.getHours() < 7) d.setDate(d.getDate() - 1);
  d.setHours(0, 0, 0, 0);
  return d;
}

export function getPlantaoParaData(date) {
  const key = toDateKey(date);
  const residenteId = PLANTOES_2026[key];
  if (!residenteId) return null;
  const r = RESIDENTES_2026.find((x) => x.id === residenteId);
  if (!r) return null;
  return { ...r, data: key, horario: getHorarioPlantao(date) };
}
