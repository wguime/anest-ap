/** Dobra de acomodação superior se aplica ao código? (item XIV) */
export function dobraAcomodacao(codigo, lista) {
  const c = String(codigo || '');
  if (LISTA_DOBRA.has(c)) return true;          // 1/2/4 explicitamente listados
  return c.startsWith('3') && lista === 'HM';   // cirúrgicos (e 31602) dobram em geral
}

/**
 * Motivo pelo qual um código NÃO dobra em acomodação superior (item XIV). Retorna a chave do
 * motivo (para texto na UI) ou null se dobra. Só faz sentido quando a acomodação é superior.
 */
export function motivoNaoDobra(codigo, lista) {
  if (dobraAcomodacao(codigo, lista)) return null;
  if (lista === 'SADT') return 'sadt';          // item VIII — SADT/diagnóstico não dobra
  return 'fora_lista';                          // item XIV — 1/2/4 fora da lista de dobra
}

/**
 * Indica se o procedimento autoriza um SEGUNDO anestesista (auxiliar = 30% do titular, item 4.8).
 * Critério OFICIAL é por tipo de alta complexidade — NÃO há limiar de porte. Heurística por
 * descrição (transplante, CEC, neonatologia cirúrgica, gastroplastia/obesidade mórbida).
 */
const RX_SEGUNDO_ANESTESISTA = /transplant|circula[çc][ãa]o extracorp|extracorp[óo]rea|\bcec\b|neonatolog|gastroplastia|obesidade m[óo]rbida/i;
export function indicaSegundoAnestesista(descricao) {
  return RX_SEGUNDO_ANESTESISTA.test(String(descricao || ''));
}

